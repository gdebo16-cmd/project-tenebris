// Generate paint and model catalogs from scripts/library-manifest.json.
// Run: node scripts/generate-library.mjs
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'scripts/library-manifest.json'), 'utf8'));

function footprintOf(kind) {
  if (kind === 'line') return [{ q: 0, r: 0 }, { q: 1, r: 0 }];
  if (kind === 'cluster') return [{ q: 0, r: 0 }, { q: 1, r: 0 }, { q: 0, r: 1 }];
  return [{ q: 0, r: 0 }];
}

function tsString(value) {
  return JSON.stringify(value);
}

function writePaintLibrary() {
  const items = manifest.textures.items;
  const lines = [
    '// Generated by scripts/generate-library.mjs from scripts/library-manifest.json. Do not edit by hand.',
    'export type BoardPaint = {',
    '    id: string;',
    '    name: string;',
    '    folder: string;',
    '    category: string;',
    '    thumb: string;',
    '};',
    '',
    'export const LIBRARY_PAINTS: readonly BoardPaint[] = [',
  ];
  for (const p of items) {
    const folder = `library/${p.id}`;
    lines.push(`    { id: ${tsString(p.id)}, name: ${tsString(p.name)}, folder: ${tsString(folder)}, category: ${tsString(p.category)}, thumb: ${tsString(`/textures/${folder}/thumb.jpg`)} },`);
  }
  lines.push('];');
  lines.push('');
  lines.push('const PAINT_BY_ID = new Map(LIBRARY_PAINTS.map((p) => [p.id, p]));');
  lines.push('');
  lines.push('export function paintById(id: string): BoardPaint | undefined {');
  lines.push('    return PAINT_BY_ID.get(id);');
  lines.push('}');
  lines.push('');
  lines.push('export function isLibraryPaint(value: unknown): value is string {');
  lines.push('    return typeof value === \'string\' && PAINT_BY_ID.has(value);');
  lines.push('}');
  lines.push('');
  fs.writeFileSync(path.join(root, 'packages/rules/src/board/paintLibrary.ts'), lines.join('\n') + '\n');
}

function modelEntry(m) {
  const id = m.id;
  const file = `/models/${id}/${id}.glb`;
  const kind = m.already === 'boulder' || id === 'boulder' ? 'boulder' : undefined;
  const fp = footprintOf(m.footprint);
  return {
    id,
    name: m.name,
    file,
    lightFile: file.replace(/\.glb$/, '.light.glb'),
    footprint: fp,
    blocksMovement: m.blocksMovement,
    blocksSight: m.blocksSight,
    category: m.category,
    ...(kind ? { kind } : {}),
  };
}

function writeModelsLibrary() {
  const items = manifest.models.items.map(modelEntry);
  const lines = [
    '// Generated by scripts/generate-library.mjs from scripts/library-manifest.json. Do not edit by hand.',
    'import { type BoardModel } from \'./models.ts\';',
    '',
    'export const LIBRARY_MODELS: readonly BoardModel[] = [',
  ];
  for (const m of items) {
    const fp = m.footprint.map((h) => `{ q: ${h.q}, r: ${h.r} }`).join(', ');
    const kind = m.kind ? `, kind: ${tsString(m.kind)}` : '';
    const cat = m.category ? `, category: ${tsString(m.category)}` : '';
    lines.push(`    { id: ${tsString(m.id)}, name: ${tsString(m.name)}, file: ${tsString(m.file)}, lightFile: ${tsString(m.lightFile)}, footprint: [${fp}], blocksMovement: ${m.blocksMovement}, blocksSight: ${m.blocksSight}${cat}${kind} },`);
  }
  lines.push('];');
  lines.push('');
  fs.writeFileSync(path.join(root, 'packages/rules/src/board/modelsLibrary.ts'), lines.join('\n') + '\n');
}

function writeContent() {
  const models = manifest.models.items.map(modelEntry);
  const paints = manifest.textures.items.map((p) => ({
    id: p.id,
    name: p.name,
    folder: `library/${p.id}`,
    category: p.category,
    thumb: `/textures/library/${p.id}/thumb.jpg`,
  }));
  fs.writeFileSync(path.join(root, 'packages/content/source/board_models.json'), JSON.stringify(models, null, 2) + '\n');
  fs.writeFileSync(path.join(root, 'packages/content/source/board_paints.json'), JSON.stringify(paints, null, 2) + '\n');
}

function writeCredits() {
  const creditsPath = path.join(root, 'assets/textures/CREDITS.md');
  let text = fs.readFileSync(creditsPath, 'utf8');
  const paintStart = /\r?\n# Library paints\r?\n/;
  const cut = text.search(paintStart);
  if (cut >= 0) text = text.slice(0, cut);
  const paintRows = manifest.textures.items.map((p) =>
    `| \`library/${p.id}\` | [${p.name}](${p.url}) | ${p.authors} |`).join('\n');
  const modelRows = manifest.models.items.filter((m) => m.id !== 'boulder').map((m) =>
    `| \`models/${m.id}\` | [${m.name}](${m.url}) | ${m.authors} |`).join('\n');
  const add = `

# Library paints

Extra board-relevant ground looks from [Poly Haven](https://polyhaven.com) (CC0), 2K JPG (colour, normal GL, roughness) plus a 1K set and a swatch thumb. Downloaded through the Poly Haven API and written by \`scripts/import-polyhaven.mjs\`.

| Folder | Poly Haven asset | Authors |
| --- | --- | --- |
${paintRows}

# Library models

Board models from [Poly Haven](https://polyhaven.com) (CC0), cleaned with \`npm run model\` (high 2K + light 1K). Boulder 01 is listed under Models above. Downloaded through the Poly Haven API.

| Folder | Poly Haven asset | Authors |
| --- | --- | --- |
${modelRows}
`;
  fs.writeFileSync(creditsPath, text.replace(/\s+$/, '') + add + '\n');
}

writePaintLibrary();
writeModelsLibrary();
writeContent();
writeCredits();
console.log('generated', manifest.textures.items.length, 'paints and', manifest.models.items.length, 'models');